-- Enterprise Data Warehouse
-- Dimensional Star Schema
-- PostgreSQL | Synthetic banking data

CREATE TABLE dim_customer (
    customer_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER NOT NULL UNIQUE,
    customer_name VARCHAR(100) NOT NULL,
    customer_segment VARCHAR(50),
    region VARCHAR(50)
);

CREATE TABLE dim_account (
    account_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id INTEGER NOT NULL UNIQUE,
    account_type VARCHAR(50) NOT NULL,
    currency_code CHAR(3) NOT NULL
);

CREATE TABLE dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year_number INTEGER NOT NULL,
    quarter_number INTEGER NOT NULL,
    month_number INTEGER NOT NULL,
    day_number INTEGER NOT NULL
);

CREATE TABLE fact_transactions (
    transaction_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id INTEGER NOT NULL UNIQUE,
    customer_key INTEGER NOT NULL,
    account_key INTEGER NOT NULL,
    date_key INTEGER NOT NULL,
    transaction_type VARCHAR(30) NOT NULL,
    transaction_status VARCHAR(20) NOT NULL,
    amount NUMERIC(18,2) NOT NULL,
    CONSTRAINT fk_customer FOREIGN KEY (customer_key)
        REFERENCES dim_customer(customer_key),
    CONSTRAINT fk_account FOREIGN KEY (account_key)
        REFERENCES dim_account(account_key),
    CONSTRAINT fk_date FOREIGN KEY (date_key)
        REFERENCES dim_date(date_key),
    CONSTRAINT chk_amount CHECK (amount > 0),
    CONSTRAINT chk_status CHECK (
        transaction_status IN ('COMPLETED', 'FAILED', 'PENDING')
    )
);

CREATE INDEX idx_fact_customer ON fact_transactions(customer_key);
CREATE INDEX idx_fact_account ON fact_transactions(account_key);
CREATE INDEX idx_fact_date ON fact_transactions(date_key);
CREATE INDEX idx_fact_status ON fact_transactions(transaction_status);
